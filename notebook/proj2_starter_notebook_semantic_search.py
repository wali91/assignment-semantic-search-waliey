if not API_KEY:
    raise RuntimeError("GEMINI_API_KEY belum diatur. Isi file .env project dengan GEMINI_API_KEY=...")

client = genai.Client(api_key=API_KEY)

EMBED_MODEL = "gemini-embedding-001"   # sesuaikan jika starter notebook memakai model lain
LLM_MODEL = "gemini-3.1-flash"         # sesuaikan jika starter notebook memakai model lain
